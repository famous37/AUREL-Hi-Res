'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const read=p=>fs.readFileSync(p,'utf8');
const main=read('app/src/main/java/com/aurel/hires/MainActivity.java');
const svc=read('app/src/main/java/com/aurel/hires/AurelPlaybackService.java');
const ui=read('app/src/main/assets/app.js');
const manifest=read('app/src/main/AndroidManifest.xml');
const policy=read('app/src/main/java/com/aurel/hires/BitPerfectOutput.java');
assert(!main.includes('setUsbVolumeFromMediaSession'));
assert(!main.includes('adjustUsbVolumeFromMediaSession'));
assert(!svc.includes('VolumeProvider'));
assert(!svc.includes('setPlaybackToRemote'));
assert(svc.includes('setPlaybackToLocal'));
assert(!manifest.includes('android.hardware.usb.action.USB_DEVICE_ATTACHED'));
assert(!ui.includes('data-aurel-usb-volume'));
assert(!ui.includes("nativeCall('setUsbVolume'"));
assert(main.includes('configureAndroidUsb(mp,false)'));
assert(policy.includes('routeUsb(mp)'));
assert(policy.includes('if(!enabled)return;'));
assert(policy.includes('phase="policy_unavailable"'));
assert(policy.includes('phase="rejected"'));
assert(policy.includes('Android playback continues.'));
let time=1000;
const context={window:{},performance:{now:()=>time}};
vm.runInNewContext(read('app/src/main/assets/aurel-progress-clock.js'),context);
const clock=context.window.AurelProgressClock;
const track={track:{id:'one'},position:1000,duration:200000,playing:true,buffering:false};
assert.equal(clock.accept(track),1000);
time=2000;track.position=500;
assert(clock.accept(track)>=1900,'Temporary clock reset cannot rewind progress');
clock.markSeek(50000);
time=2100;track.position=1100;
assert.equal(clock.accept(track),50000,'Old samples after seeking must not bounce the slider');
time=2200;track.position=50010;
assert(clock.accept(track)>=50000,'Seek updates restore timeline');
time=2400;track.track={id:'two'};track.position=0;
assert.equal(clock.accept(track),0,'New song resets clock');
console.log('Android native media volume and stable progress PASS');
