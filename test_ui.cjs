const fs=require('fs'), vm=require('vm'), assert=require('assert');
const base=__dirname+'/app/src/main/assets/';
const elem=()=>({innerHTML:'',value:'',textContent:'',dataset:{},classList:{add(){},remove(){},toggle(){}},addEventListener(){},querySelector(){return null},setAttribute(){},style:{setProperty(){}}});
const nodes=new Map(),listeners={};
const doc={querySelector(s){if(!nodes.has(s))nodes.set(s,elem());return nodes.get(s)},querySelectorAll(){return[]},addEventListener(n,fn){(listeners[n]??=[]).push(fn)}};
const store=new Map(), ls={getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v),removeItem:k=>store.delete(k)};
const win={AurelNative:null};const ctx=vm.createContext({document:doc,window:win,localStorage:ls,console,URL,Map,Promise,setTimeout,clearTimeout,JSON,Error});
vm.runInContext(fs.readFileSync(base+'app.js','utf8'),ctx,{filename:'app.js'});
vm.runInContext(fs.readFileSync(base+'modern.js','utf8'),ctx,{filename:'modern.js'});
const evalJs=s=>vm.runInContext(s,ctx);
const cover='https://static.qobuz.com/images/covers/fl/al/123_600.jpg';
assert.equal(evalJs(`image({album:{image:{large:'${cover}'}}})`),cover);
assert.equal(evalJs(`image({image:{},album:{image:{large:'${cover}'}}})`),cover);
assert.equal(evalJs(`image({image:'https://example.com/a.jpg'})`),'');
// Diverse Qobuz artist encodings from release, artist, album and track payloads.
assert.equal(evalJs(`artist({artists:[{id:90,name:'Black Sabbath'}]})`),'Black Sabbath');
assert.equal(evalJs(`artist({album:{artist:{id:99,name:{display:'Benjamin Alard'}}}})`),'Benjamin Alard');
assert.equal(evalJs(`artist({performer:{name:'Bruce Springsteen'}})`),'Bruce Springsteen');
assert.equal(evalJs(`artistId({album:{artist:{id:99,name:'Benjamin Alard'}}})`),'99');
assert.equal(evalJs(`artist({artists:{items:[{id:78,name:'Aphex Twin'}]}})`),'Aphex Twin');
evalJs(`app.session={loggedIn:true,streamConnected:true,libraryConnected:false,quality:27,profile:{displayName:'Test account'}};app.albums=[{id:'100',title:'Example',artists:[{id:5,name:'Bach'}]}];renderHome()`);
assert(nodes.get('#screen').innerHTML.includes('Bach'));
assert(!nodes.get('#screen').innerHTML.includes('Unknown artist'));
evalJs(`app.nav='search';window.AurelSearchHistory('Black Sabbath');renderSearch()`);
assert(nodes.get('#screen').innerHTML.includes('Recent searches'));
evalJs(`app.nav='library';app.libType='playlists';app.playlists=[{id:20,name:'Music',tracks_count:5}];renderLibrary()`);
assert(nodes.get('#screen').innerHTML.includes('Music'));
evalJs(`app.player={track:{id:1,title:'War Pigs',artist:{id:43840,name:'Black Sabbath'},album:{id:'072435',title:'Paranoid'}},queue:[{id:1,title:'A'},{id:2,title:'C'}],index:0,count:2,duration:300000,position:40000,bits:24,sampleRateHz:96000,sourceVerified:true,codec:'FLAC',playing:true};app.overlay=true;drawOverlay()`);
assert(nodes.get('#overlay').innerHTML.includes('Now playing'));
assert(nodes.get('#overlay').innerHTML.includes('data-open-playing-artist'));
assert(nodes.get('#overlay').innerHTML.includes('Black Sabbath'));
assert(nodes.get('#overlay').innerHTML.includes('data-open-playing-album'));
assert(nodes.get('#overlay').innerHTML.includes('24-bit / 96 kHz'));
assert(!nodes.get('#overlay').innerHTML.toLowerCase().includes('download'));
assert(nodes.get('#overlay').innerHTML.includes('data-player-sheet="audio"'));
assert(nodes.get('#overlay').innerHTML.includes('svg'));
evalJs(`app.playerSheet='upnext';drawOverlay()`);
assert(nodes.get('#overlay').innerHTML.includes('data-queue-play="1"'));
evalJs(`app.playerSheet='audio';drawOverlay()`);
assert(nodes.get('#overlay').innerHTML.includes('Android mixer'));
evalJs(`app.nav='settings';renderSettings()`);
assert(!nodes.get('#screen').innerHTML.toLowerCase().includes('download'));
evalJs(`app.selected={id:43840,name:'Black Sabbath',albums:{items:[{id:'10',title:'Paranoid',image:{large:'${cover}'}}],total:1}};app.selectedKind='artist';renderArtist()`);
assert(nodes.get('#screen').innerHTML.includes('Discography'));
assert(nodes.get('#screen').innerHTML.includes('Paranoid'));
assert(!nodes.get('#screen').innerHTML.toLowerCase().includes('download'));
for(const name of ['app.js','modern.js']) assert(!fs.readFileSync(base+name,'utf8').includes('data-download'));
assert(!fs.readFileSync(base+'app.js','utf8').includes('data-eq-save'));
const java=fs.readFileSync(__dirname+'/app/src/main/java/com/aurel/hires/MainActivity.java','utf8');
for(const name of ['downloadTrack','downloadArtist','playDownloaded','downloadedFiles']) assert(!java.includes(name));
console.log('AUREL v0.5 UI checks passed — artist metadata, discography, Qobuz-like player, no download actions, audio state.');
