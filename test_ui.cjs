const fs=require('fs'), vm=require('vm'), assert=require('assert');
const base=__dirname+'/app/src/main/assets/';
const elem=()=>({innerHTML:'',value:'',textContent:'',dataset:{},classList:{add(){},remove(){},toggle(){}},addEventListener(){},querySelector(){return null},setAttribute(){},style:{setProperty(){}}});
const nodes=new Map(),listeners={};
const doc={querySelector(s){if(!nodes.has(s))nodes.set(s,elem());return nodes.get(s)},querySelectorAll(){return[]},addEventListener(n,fn){(listeners[n]??=[]).push(fn)}};
const store=new Map(), ls={getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v),removeItem:k=>store.delete(k)};
const win={AurelNative:null};const ctx=vm.createContext({document:doc,window:win,localStorage:ls,console,URL,Map,Promise,setTimeout,clearTimeout,JSON,Error});
vm.runInContext(fs.readFileSync(base+'app.js','utf8'),ctx,{filename:'app.js'});
vm.runInContext(fs.readFileSync(base+'modern.js','utf8'),ctx,{filename:'modern.js'});
const cover='https://static.qobuz.com/images/covers/fl/al/123_600.jpg';
assert.equal(vm.runInContext(`image({album:{image:{large:'${cover}'}}})`,ctx),cover);
assert.equal(vm.runInContext(`image({image:{},album:{image:{large:'${cover}'}}})`,ctx),cover);
assert.equal(vm.runInContext(`image({image:'https://example.com/a.jpg'})`,ctx),'');
vm.runInContext(`app.session={loggedIn:true,streamConnected:true,libraryConnected:false,quality:27,profile:{displayName:'Test account'}};app.albums=[{id:'100',title:'Example',artist:{name:'Artist'}}];renderHome()`,ctx);
assert(nodes.get('#screen').innerHTML.includes('Fresh on Qobuz'));
vm.runInContext(`app.nav='magazine';renderMagazine()`,ctx);
assert(nodes.get('#screen').innerHTML.includes('Read Qobuz Magazine'));
vm.runInContext(`app.nav='search';window.AurelSearchHistory('Black Sabbath');renderSearch()`,ctx);
assert(nodes.get('#screen').innerHTML.includes('Recent searches'));
vm.runInContext(`app.nav='library';app.libType='playlists';app.playlists=[{id:20,name:'Music',tracks_count:5}];renderLibrary()`,ctx);
assert(nodes.get('#screen').innerHTML.includes('Playlists'));
assert(nodes.get('#screen').innerHTML.includes('Music'));
vm.runInContext(`app.player={track:{id:1,title:'A',artist:{name:'B'}},queue:[{id:1,title:'A'},{id:2,title:'C'}],index:0,count:2,duration:300000,position:40000,bits:24,sampleRate:96,playing:true};app.overlay=true;drawOverlay()`,ctx);
assert(nodes.get('#overlay').innerHTML.includes('Now playing'));
assert(nodes.get('#overlay').innerHTML.includes('Source quality not verified'));
assert(nodes.get('#overlay').innerHTML.includes('data-download-playing'));
assert(nodes.get('#overlay').innerHTML.includes('data-queue-play="1"'));
vm.runInContext(`app.playerSheet='audio';drawOverlay()`,ctx);
assert(nodes.get('#overlay').innerHTML.includes('Android mixer'));
assert(nodes.get('#overlay').innerHTML.includes('Not verified by Qobuz API'));
vm.runInContext(`app.player={track:{id:1,title:'Music'},bits:24,sampleRateHz:96000,sourceVerified:true,codec:'FLAC'}; app.playerSheet='audio';drawOverlay()`,ctx);
assert(nodes.get('#overlay').innerHTML.includes('24-bit / 96 kHz'));
vm.runInContext(`app.downloaded={items:[{name:'Purchased - 123.flac',bytes:1024}]};app.nav='downloads';renderDownloads()`,ctx);
assert(nodes.get('#screen').innerHTML.includes('Purchased - 123.flac'));
assert(!fs.readFileSync(base+'app.js','utf8').includes('data-eq-save'));
console.log('AUREL v0.4 UI tests passed: artwork, navigation, downloads, quality Hz conversion, queue, no equalizer.');
